import {
  cpSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { PACKAGE_CACHE_MARKER } from "@stateward/core/internal";
import { main } from "../src/main.js";
import type { CliEnv, ExitCode } from "../src/main.js";

/**
 * `stateward deps` and `stateward cache` on the Errors pack's library-facts fixture: a project
 * whose fake node_modules has one package per source of facts and per reason one is unknown.
 */
const source = fileURLToPath(
  new URL("../../plugin-errors/test/fixtures/library-facts", import.meta.url),
);
const pluginErrors = new URL("../../plugin-errors/dist/index.js", import.meta.url).href;

let base = "";
let project = "";
let cacheDir = "";
const saved = process.env.STATEWARD_PACKAGE_CACHE_DIR;

beforeAll(() => {
  base = mkdtempSync(path.join(tmpdir(), "stateward-deps-"));
  project = path.join(base, "app");
  cacheDir = path.join(base, "package-cache");
  cpSync(source, project, { recursive: true });
  cpSync(path.join(source, "packages"), path.join(project, "node_modules"), { recursive: true });
  rmSync(path.join(project, "packages"), { recursive: true, force: true });
  // `large-lib` is generated by the plugin's test; here the import stays unresolved.
  writeFileSync(
    path.join(project, "stateward.config.mjs"),
    [
      `import { errors } from ${JSON.stringify(pluginErrors)};`,
      "export default {",
      '  preset: "recommended",',
      "  plugins: [errors()],",
      '  facts: { "config-lib": { go: { throws: ["ConfigError"] }, later: { throws: ["ConfigError"] } } },',
      "};",
      "",
    ].join("\n"),
  );
  process.env.STATEWARD_PACKAGE_CACHE_DIR = cacheDir;
});

afterAll(() => {
  if (saved === undefined) delete process.env.STATEWARD_PACKAGE_CACHE_DIR;
  else process.env.STATEWARD_PACKAGE_CACHE_DIR = saved;
  rmSync(base, { recursive: true, force: true });
});

async function run(
  argv: readonly string[],
  resultsDir?: string,
): Promise<{ code: ExitCode; stdout: string; stderr: string }> {
  let stdout = "";
  let stderr = "";
  const env: CliEnv = {
    cwd: project,
    stdout: (text) => (stdout += text),
    stderr: (text) => (stderr += text),
    color: false,
    ...(resultsDir === undefined ? {} : { cacheDir: () => resultsDir }),
  };
  const code = await main(argv, env);
  return { code, stdout, stderr };
}

describe("stateward deps", { timeout: 30_000 }, () => {
  it("prints each package called, its version, how its facts are known and why the rest is not", async () => {
    const { code, stdout, stderr } = await run(["deps"]);
    expect(stderr).toBe("");
    expect(code).toBe(0);
    expect(stdout).toBe(
      [
        "package       version  facts             called  mapped  unknown, and why",
        "cjs-lib       0.3.0    inferred               1       1",
        "config-lib    3.0.0    config                 2       2",
        "declared-lib  1.2.3    declared               2       2",
        "eval-lib      0.1.0    unknown                1       0  eval; add facts in your config",
        "inferred-lib  2.0.1    inferred+unknown       3       1  2: each (calls a callback), missing (not found in its source)",
        "minified-lib  4.17.21  unknown                1       0  minified; add facts in your config",
        "native-lib    1.0.0    unknown                1       0  native addon; add facts in your config",
        "",
      ].join("\n"),
    );
  });

  it("prints the same as JSON", async () => {
    const { code, stdout } = await run(["deps", "--format", "json"]);
    expect(code).toBe(0);
    const parsed: unknown = JSON.parse(stdout);
    const rows: unknown =
      typeof parsed === "object" && parsed !== null ? Reflect.get(parsed, "packages") : undefined;
    expect(Array.isArray(rows) ? rows.length : 0).toBe(7);
    expect(Array.isArray(rows) ? rows[4] : undefined).toEqual({
      package: "inferred-lib",
      version: "2.0.1",
      facts: "inferred+unknown",
      called: 3,
      mapped: 1,
      unknown: [
        { function: "each", reasons: ["calls a callback"] },
        { function: "missing", reasons: ["not found in its source"] },
      ],
    });
  });
});

describe("stateward cache", { timeout: 30_000 }, () => {
  it("shows the package cache's size, and clean removes only it, saying what it removed", async () => {
    await run(["deps"]);
    const stats = await run(["cache", "stats"]);
    expect(stats.code).toBe(0);
    expect(stats.stdout).toMatch(
      new RegExp(
        `^package cache: ${cacheDir.replaceAll("\\", "\\\\")}\\n  \\d+ entries, [\\d.]+ (?:bytes|KB) of at most 200\\.0 MB \\(STATEWARD_PACKAGE_CACHE_MAX_MB\\)\\nresults cache: none for this project \\(.*\\)\\n$`,
      ),
    );
    const clean = await run(["cache", "clean"]);
    expect(clean.code).toBe(0);
    expect(clean.stdout).toMatch(
      /^removed the package cache .+: \d+ entries, [\d.]+ (?:bytes|KB)\n$/,
    );
    expect(existsSync(cacheDir)).toBe(false);
    expect(existsSync(project)).toBe(true);
    const again = await run(["cache", "clean"]);
    expect(again.stdout).toBe(`the package cache is already empty: ${cacheDir}\n`);
  });

  it("shows the project's results cache too, and clean removes both", async () => {
    const results = path.join(base, "results");
    await run(["check"], results);
    const stats = await run(["cache", "stats"], results);
    expect(stats.code).toBe(0);
    expect(stats.stdout).toMatch(
      new RegExp(
        `\\nresults cache: ${results.replaceAll("\\", "\\\\")}\\n  1 file, [\\d.]+ (?:bytes|KB) of at most 200\\.0 MB \\(STATEWARD_CACHE_MAX_MB\\)\\n$`,
      ),
    );
    const clean = await run(["cache", "clean"], results);
    expect(clean.code).toBe(0);
    expect(clean.stdout).toMatch(
      // The facts were known to this process already, so the package cache may have stayed empty.
      /^(?:removed the package cache .+: \d+ entries, [\d.]+ (?:bytes|KB)|the package cache is already empty: .+)\nremoved the results cache .+: 1 file, [\d.]+ (?:bytes|KB)\n$/,
    );
    expect(existsSync(results)).toBe(false);
    const again = await run(["cache", "clean"], results);
    expect(again.stdout).toBe(
      `the package cache is already empty: ${cacheDir}\nthe results cache is already empty: ${results}\n`,
    );
  });

  it("clean refuses a folder holding something else, and removes nothing", async () => {
    // The facts of this process are known already, so `deps` writes nothing: a cache by hand.
    mkdirSync(cacheDir, { recursive: true });
    writeFileSync(path.join(cacheDir, PACKAGE_CACHE_MARKER), "");
    const other = path.join(cacheDir, "notes.txt");
    writeFileSync(other, "not stateward's");
    const clean = await run(["cache", "clean"]);
    expect(clean.code).toBe(2);
    expect(clean.stderr).toBe(
      `stateward: cache clean removed nothing from ${cacheDir}: it holds \`notes.txt\`, which is not a package's folder of stateward's cache\n`,
    );
    expect(readFileSync(other, "utf8")).toBe("not stateward's");
    rmSync(other);
    expect((await run(["cache", "clean"])).code).toBe(0);
  });

  it("takes stats or clean", async () => {
    const { code, stderr } = await run(["cache", "purge"]);
    expect(code).toBe(2);
    expect(stderr).toMatch(
      /^stateward: cache needs "stats" \(show its size\) or "clean" \(delete it\)\n/,
    );
  });
});
