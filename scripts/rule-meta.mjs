// The packs, loaded with every rule's code, and each pack's generated src/rules.meta.ts: what the
// pack declares up front so a rule's code loads only when the rule is on.
// Used by scripts/docs.mjs, which writes and checks these files with the docs.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { format, resolveConfig } from "prettier";
import { PACK_CATALOG } from "stateward";

/** `@stateward/plugin-unions` -> `plugin-unions`. */
const folderOf = (packageName) => packageName.replace(/^@stateward\//, "");

/**
 * Every pack of the catalog, built (dist), with each rule's code loaded. A lazy rule is loaded as
 * its module defines it, without comparing it with its declaration: that comparison is what the
 * generated file is checked by, so a stale declaration must not stop it from being generated.
 */
export async function loadPacks(root) {
  const packs = [];
  for (const entry of PACK_CATALOG) {
    const folder = folderOf(entry.packageName);
    const dist = path.join(root, "packages", folder, "dist");
    await declareNewRules(dist);
    const url = pathToFileURL(path.join(dist, "index.js"));
    const plugin = (await import(url.href))[entry.importName]();
    const rules = {};
    for (const [key, rule] of Object.entries(plugin.rules)) {
      rules[key] = rule.kind === "lazy" ? await rule.load() : rule;
    }
    packs.push({ folder, plugin: { ...plugin, rules } });
  }
  return packs;
}

/**
 * A rule just added to a pack's plugin.ts has no entry in its generated rules.meta.ts yet, and the
 * pack cannot even be created without one (`lazyRule` reads it). Generating the entry is this
 * script's job, so the built rules.meta.js gets a stand-in for each missing rule: the rule's own
 * module says the rest, and the next build replaces the file. Adding a rule is then: write it,
 * build, `pnpm run docs`, build again.
 */
async function declareNewRules(dist) {
  const metaFile = path.join(dist, "rules.meta.js");
  let pluginText;
  let metaText;
  try {
    pluginText = readFileSync(path.join(dist, "plugin.js"), "utf8");
    metaText = readFileSync(metaFile, "utf8");
  } catch {
    return;
  }
  // A separate URL from the one plugin.js imports, so the file can still change before that.
  const { RULES } = await import(`${pathToFileURL(metaFile).href}?keys=${String(Date.now())}`);
  const used = [
    ...pluginText.matchAll(/\bRULES\[\s*"([^"]+)"\s*\]|\bRULES\.([A-Za-z_$][\w$]*)/g),
  ].map((match) => match[1] ?? match[2]);
  const missing = [...new Set(used)].filter((key) => !Object.hasOwn(RULES, key));
  if (missing.length === 0) return;
  const standIns = missing.map(
    (key) => `RULES[${JSON.stringify(key)}] = { kind: "file", meta: {} };`,
  );
  writeFileSync(metaFile, `${metaText.trimEnd()}\n${standIns.join("\n")}\n`);
}

const HEADER = [
  "// Generated by pnpm run docs from the rule modules; do not edit. What each rule declares up",
  "// front (its kind and metadata, without `explain`), so its code loads only when it is on.",
].join("\n");

/** The text of one pack's src/rules.meta.ts. */
async function metaFile(root, folder, plugin) {
  const entries = Object.entries(plugin.rules).map(([key, rule]) => {
    const meta = Object.fromEntries(
      Object.entries(rule.meta).filter(([name]) => name !== "explain"),
    );
    return `${JSON.stringify(key)}: ${JSON.stringify({ kind: rule.kind, meta })},`;
  });
  const file = path.join(root, "packages", folder, "src", "rules.meta.ts");
  const text = [
    HEADER,
    'import type { RuleDeclaration } from "@stateward/core";',
    "",
    "export const RULES = {",
    ...entries,
    "} as const satisfies Readonly<Record<string, RuleDeclaration>>;",
    "",
  ].join("\n");
  const options = (await resolveConfig(file)) ?? {};
  return format(text, { ...options, filepath: file });
}

/** Every pack's generated rules.meta.ts: path relative to the repo root, and its text. */
export async function metaFiles(root, packs) {
  const files = new Map();
  for (const { folder, plugin } of packs) {
    files.set(`packages/${folder}/src/rules.meta.ts`, await metaFile(root, folder, plugin));
  }
  return files;
}
