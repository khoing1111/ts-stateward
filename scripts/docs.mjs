// Generates docs/packs/<plugin>.md and docs/rules/<plugin>/<rule>.md from the built plugins, and
// each pack's src/rules.meta.ts (scripts/rule-meta.mjs).
//   node scripts/docs.mjs           writes the files
//   node scripts/docs.mjs --check   fails, listing the files, when they differ from what is on disk
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { PRESETS, RULE_TIERS, ruleSetting } from "@stateward/core/internal";
import { explainSectionProblems, importNameOf } from "stateward";
import { loadPacks, metaFiles } from "./rule-meta.mjs";
import { ALL_ADDONS } from "./try-config.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const HEADER = "<!-- Generated by pnpm run docs; do not edit. -->";
const TIER_TITLES = { core: "Core", coverage: "Coverage", addon: "Add-on" };
/** What a rule's tier means for the reader of its page, in one plain line. */
const TIER_MEANING = {
  core: "core (on in every preset)",
  coverage: "coverage (info under `recommended`, an error under `strict`)",
  addon: "add-on (off until you list its add-on)",
};

// The packs with every rule's code loaded: the pages need each rule's explain text.
const packs = await loadPacks(root);
const plugins = packs.map((pack) => pack.plugin);

/** The severity of a rule under a preset; an add-on rule is shown with its add-on listed. */
function severityUnder(plugin, key, meta, preset) {
  const addons = meta.addon === undefined ? [] : [`${plugin.name}/${meta.addon}`];
  return ruleSetting({ preset, addons, rules: {}, groups: {} }, plugin.name, key, meta);
}

function severityCells(plugin, key, meta) {
  return PRESETS.map((preset) => severityUnder(plugin, key, meta, preset));
}

function ruleEntries(plugin) {
  return Object.entries(plugin.rules).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
}

const TYPE_NAMES = {
  boolean: "boolean",
  number: "number",
  string: "string",
  strings: "list of strings",
  record: "object of names to lists of strings",
  severities: 'object of kinds to "error", "warning", "info" or "off"',
};

/** What an option does; a severity per kind also names each kind and what it is. */
function optionText(option) {
  if (option.kind !== "severities") return option.description;
  const kinds = Object.entries(option.kinds).map(
    ([kind, text]) => `\`${kind}\`: ${text.replace(/\.$/, "")}`,
  );
  return `${option.description} Kinds: ${kinds.join("; ")}.`;
}

function cell(text) {
  return text.replaceAll("|", "\\|");
}

/** Name, type, default and description of each option a rule declares; empty when none. */
function optionRows(spec) {
  return Object.entries(spec ?? {}).map(([name, option]) => {
    const limits = [
      option.oneOf === undefined
        ? ""
        : `one of ${option.oneOf.map((v) => JSON.stringify(v)).join(", ")}`,
      option.integer === true ? "whole number" : "",
      option.min === undefined ? "" : `min ${option.min}`,
      option.max === undefined ? "" : `max ${option.max}`,
    ].filter((part) => part !== "");
    const type = [TYPE_NAMES[option.kind], ...limits].join(", ");
    return `| \`${name}\` | ${cell(type)} | \`${cell(JSON.stringify(option.default))}\` | ${cell(optionText(option))} |`;
  });
}

const OPTION_HEAD = ["| Option | Type | Default | What it does |", "| --- | --- | --- | --- |"];

function packOptionLines(plugin) {
  const lines = [];
  for (const [key, rule] of ruleEntries(plugin)) {
    const rows = optionRows(rule.meta.options);
    if (rows.length === 0) continue;
    lines.push(`### ${key}`, "", ...OPTION_HEAD, ...rows, "");
  }
  if (lines.length === 0) return [];
  return [
    "## Options",
    "",
    'Set in the config as `rules: { "<rule>": [severity, { option: value }] }`.',
    "",
    ...lines,
  ];
}

/** The pack's groups, sorted: they are derived from the rules, a pack lists none of its own. */
function groupNames(plugin) {
  return [...new Set(Object.values(plugin.rules).map((rule) => rule.meta.group))].sort();
}

function groupIntro(plugin) {
  const [first] = groupNames(plugin);
  return [
    `Rules sit under their group. Set a whole group in the config, \`groups: { "${plugin.name}/${first ?? "group"}": "warning" }\`, or one rule under \`rules\`; a rule's own entry wins.`,
    "",
  ];
}

function packPage(plugin) {
  const lines = [HEADER, "", `# ${plugin.name}`, "", plugin.description, ""];
  lines.push("## Rules", "", ...groupIntro(plugin));
  for (const group of groupNames(plugin)) {
    lines.push(`### ${group}`, "");
    lines.push(
      "| Rule | Kind | recommended | strict | What it checks |",
      "| --- | --- | --- | --- | --- |",
    );
    const rules = ruleEntries(plugin).filter(([, rule]) => rule.meta.group === group);
    for (const tier of RULE_TIERS) {
      for (const [key, rule] of rules.filter(([, entry]) => entry.meta.tier === tier)) {
        const [recommended, strict] = severityCells(plugin, key, rule.meta);
        const kind = tier === "addon" ? `Add-on \`${rule.meta.addon ?? ""}\`` : TIER_TITLES[tier];
        const heuristic = rule.meta.heuristic === true ? " (heuristic)" : "";
        lines.push(
          `| [${key}](../rules/${plugin.name}/${key}.md) | ${kind} | ${recommended} | ${strict} | ${rule.meta.description}${heuristic} |`,
        );
      }
    }
    lines.push("");
  }
  lines.push(...packOptionLines(plugin));
  lines.push(
    "## Add-ons",
    "",
    ...addonLines(plugin),
    "",
    "## Settings",
    "",
    "Presets and add-ons are set in the config, not on the plugin:",
    "",
    "```ts",
    "export default defineConfig({",
    `  plugins: [${importNameOf(plugin)}()],`,
    '  preset: "strict",',
    '  // addons: ["' + plugin.name + '/<addon>"],',
    "});",
    "```",
    "",
  );
  return lines.join("\n");
}

/** The add-ons a rule belongs to (an add-on rule) or is widened by (a core or coverage rule). */
function addonsOf(rule) {
  return [
    ...(rule.meta.addon === undefined ? [] : [rule.meta.addon]),
    ...(rule.meta.widenedBy ?? []),
  ];
}

function addonLines(plugin) {
  const names = [...new Set(Object.values(plugin.rules).flatMap(addonsOf))].sort();
  if (names.length === 0) return ["None yet."];
  return names.map((name) => {
    const rules = ruleEntries(plugin)
      .filter(([, rule]) => addonsOf(rule).includes(name))
      .map(
        ([key, rule]) => `\`${key}\`${rule.meta.addon === name ? "" : " (checks more with it)"}`,
      );
    return `- \`${plugin.name}/${name}\`: ${rules.join(", ")}`;
  });
}

function rulePage(plugin, key, rule) {
  const id = `${plugin.name}/${key}`;
  const [recommended, strict] = severityCells(plugin, key, rule.meta);
  const lines = [
    HEADER,
    "",
    `# ${id}`,
    "",
    rule.meta.description,
    "",
    `- Group: ${plugin.name}/${rule.meta.group}`,
    `- Tier: ${TIER_MEANING[rule.meta.tier]}`,
    `- Add-on: ${rule.meta.addon === undefined ? "none" : `${plugin.name}/${rule.meta.addon}`}`,
    ...(rule.meta.widenedBy === undefined
      ? []
      : [
          `- Checks more with the add-ons: ${rule.meta.widenedBy.map((name) => `${plugin.name}/${name}`).join(", ")}`,
        ]),
    `- Heuristic: ${rule.meta.heuristic === true ? "yes: it guesses, so it is never an error unless you set it" : "no"}`,
    `- Severity under \`recommended\`: ${recommended}`,
    `- Severity under \`strict\`: ${strict}`,
    "",
  ];
  // The page opens with the summary line above, so the explain text's own summary is not repeated.
  const explain = rule.meta.explain
    .replace(`# ${id}\n`, "")
    .trimStart()
    .replace(`${rule.meta.description}\n`, "")
    .trimStart();
  lines.push(explain.trimEnd(), "");
  const rows = optionRows(rule.meta.options);
  if (rows.length > 0) {
    // "Turn it on or off" is the last section: the options table closes it.
    lines.push(
      "### Options",
      "",
      `Set as \`rules: { "${id}": ["${recommended === "off" ? "error" : recommended}", { … }] }\`.`,
      "",
      ...OPTION_HEAD,
      ...rows,
      "",
    );
  }
  return lines.join("\n");
}

/** Every generated file: path relative to the repo root, and its text. */
async function generate() {
  const files = await metaFiles(root, packs);
  for (const plugin of plugins) {
    files.set(`docs/packs/${plugin.name}.md`, packPage(plugin));
    for (const [key, rule] of ruleEntries(plugin)) {
      files.set(`docs/rules/${plugin.name}/${key}.md`, rulePage(plugin, key, rule));
    }
  }
  return files;
}

function markdownFilesUnder(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) return markdownFilesUnder(full);
    return entry.name.endsWith(".md") ? [path.relative(root, full).split(path.sep).join("/")] : [];
  });
}

// The bundled rules only: a team's own rules are the team's (docs/user/write-your-own-rule.md).
const sectionProblems = plugins.flatMap((plugin) =>
  ruleEntries(plugin).flatMap(([key, rule]) =>
    explainSectionProblems(`${plugin.name}/${key}`, rule.meta.explain),
  ),
);
if (sectionProblems.length > 0) {
  console.error(
    `Rule explain texts are incomplete:\n${sectionProblems.map((p) => `  ${p}`).join("\n")}`,
  );
  console.error("Every bundled rule has the sections the rule pages need.");
  process.exit(1);
}

// `pnpm try` and the corpus turn on every add-on from one list; a new add-on must be in it.
const declaredAddons = plugins
  .flatMap((plugin) =>
    Object.values(plugin.rules).flatMap((rule) =>
      addonsOf(rule).map((name) => `${plugin.name}/${name}`),
    ),
  )
  .filter((name, index, all) => all.indexOf(name) === index)
  .sort();
const listedAddons = [...ALL_ADDONS].sort();
if (declaredAddons.join(",") !== listedAddons.join(",")) {
  console.error(
    `ALL_ADDONS in scripts/try-config.mjs (${listedAddons.join(", ")}) differs from the add-ons the packs declare (${declaredAddons.join(", ")}).`,
  );
  process.exit(1);
}

const generated = await generate();
const onDisk = [
  ...markdownFilesUnder(path.join(root, "docs/packs")),
  ...markdownFilesUnder(path.join(root, "docs/rules")),
];
const stale = onDisk.filter((file) => !generated.has(file));

if (process.argv.includes("--check")) {
  const differing = [...generated].filter(([file, text]) => {
    const full = path.join(root, file);
    return !existsSync(full) || readFileSync(full, "utf8") !== text;
  });
  const problems = [
    ...differing.map(([file]) => `${file} differs from the generated text`),
    ...stale.map((file) => `${file} is not generated any more`),
  ];
  if (problems.length > 0) {
    console.error(`Generated files are out of date:\n${problems.map((p) => `  ${p}`).join("\n")}`);
    console.error("Run: pnpm run docs");
    process.exit(1);
  }
  console.log(`${String(generated.size)} generated files are current.`);
} else {
  for (const file of stale) rmSync(path.join(root, file));
  for (const [file, text] of generated) {
    const full = path.join(root, file);
    mkdirSync(path.dirname(full), { recursive: true });
    writeFileSync(full, text);
  }
  console.log(
    `Wrote ${String(generated.size)} files under docs/packs, docs/rules and packages/*/src/rules.meta.ts.`,
  );
}
