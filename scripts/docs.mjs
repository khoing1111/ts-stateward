/** The severity of a rule under a preset; an add-on rule is shown with its add-on listed. */
function severityUnder(plugin, key, meta, preset) {
  const addons = meta.addon === undefined ? [] : [`${plugin.name}/${meta.addon}`];
  return ruleSetting({ preset, addons, rules: {}, groups: {} }, plugin.name, key, meta);
}

function severityCells(plugin, key, meta) {
  return PRESETS.map((preset) => severityUnder(plugin, key, meta, preset));
}

function ruleEntries(plugin) {
  return Object.entries(plugin.rules).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
}

const TYPE_NAMES = {
  boolean: "boolean",
  number: "number",
  string: "string",
  strings: "list of strings",
  record: "object of names to lists of strings",
  severities: 'object of kinds to "error", "warning", "info" or "off"',
};

/** What an option does; a severity per kind also names each kind and what it is. */
function optionText(option) {
  if (option.kind !== "severities") return option.description;
  const kinds = Object.entries(option.kinds).map(
    ([kind, text]) => `\`${kind}\`: ${text.replace(/\.$/, "")}`,
  );
  return `${option.description} Kinds: ${kinds.join("; ")}.`;
}

function cell(text) {
  return text.replaceAll("|", "\\|");
}

/** Name, type, default and description of each option a rule declares; empty when none. */
function optionRows(spec) {
  return Object.entries(spec ?? {}).map(([name, option]) => {
    const limits = [
      option.oneOf === undefined
        ? ""
        : `one of ${option.oneOf.map((v) => JSON.stringify(v)).join(", ")}`,
      option.integer === true ? "whole number" : "",
      option.min === undefined ? "" : `min ${option.min}`,
      option.max === undefined ? "" : `max ${option.max}`,
    ].filter((part) => part !== "");
    const type = [TYPE_NAMES[option.kind], ...limits].join(", ");
    return `| \`${name}\` | ${cell(type)} | \`${cell(JSON.stringify(option.default))}\` | ${cell(optionText(option))} |`;
  });
}

const OPTION_HEAD = ["| Option | Type | Default | What it does |", "| --- | --- | --- | --- |"];

/** The pack's groups, sorted: they are derived from the rules, a pack lists none of its own. */
function groupNames(plugin) {
  return [...new Set(Object.values(plugin.rules).map((rule) => rule.meta.group))].sort();
}

/** "error under `recommended` and `strict`", or "info under `recommended`, error under `strict`". */
function severityPhrase(recommended, strict) {
  return recommended === strict
    ? `${recommended} under \`recommended\` and \`strict\``
    : `${recommended} under \`recommended\`, ${strict} under \`strict\``;
}

/** When a rule is on and how loud, in one line: its kind, add-on, guess, group. */
function ruleStatus(plugin, key, meta) {
  const [recommended, strict] = severityCells(plugin, key, meta);
  const severity = severityPhrase(recommended, strict);
  const kind = {
    core: `Core rule: ${severity}.`,
    coverage: `Coverage rule (it points at code whose types do not say enough to check it): ${severity}.`,
    addon: `Add-on rule, off until you list \`${plugin.name}/${meta.addon ?? ""}\` in \`addons\`; then ${severity}.`,
  }[meta.tier];
  const widened =
    meta.widenedBy === undefined
      ? ""
      : ` It checks more with the add-ons ${meta.widenedBy.map((name) => `\`${plugin.name}/${name}\``).join(", ")}.`;
  const guess =
    meta.heuristic === true
      ? " It judges from patterns in the code, not only from types, so it can be wrong: it is never an error unless you make it one."
      : "";
  return `${kind}${widened}${guess} Group: \`${plugin.name}/${meta.group}\`.`;
}

/**
 * A rule's examples as a pack page shows them: the bad code (all of it when short, else the
 * lines around the finding), the first line stateward prints, and the fix in one sentence.
 */
function packExample(example) {
  const bad = example.blocks.filter((block) => block.role === "bad");
  const block = bad.find((entry) => entry.file === example.first?.file) ?? bad[0];
  const shown = excerpt(block.code.split("\n"), (example.first?.line ?? 1) - 1);
  return [
    `\`\`\`${block.lang}`,
    ...shown,
    "```",
    "",
    "```text",
    example.first?.headline ?? "",
    "```",
    "",
    `Fix: ${fixSentence(example)}`,
  ];
}

/**
 * The lines of a bad example a pack page shows: all of them when they are few, else the top-level
 * declaration the finding is in (its first line to its closing line, with the ones above when it is
 * short), cut around the finding when even that is long.
 */
function excerpt(lines, at) {
  const MAX = 12;
  if (lines.length <= MAX) return lines;
  const topLevel = (line) => line !== "" && !/^\s/.test(line);
  const closing = (line) => /^[)}\]]/.test(line);
  let start = at;
  while (start > 0 && !(topLevel(lines[start] ?? "") && !closing(lines[start] ?? ""))) start -= 1;
  let end = at;
  const opener = lines[start] ?? "";
  if (!(start === at && /;$/.test(opener))) {
    while (end < lines.length - 1 && !closing(lines[end] ?? "")) end += 1;
  }
  // A one-line statement (`createRoot(…).render(<Profile />)`) says little alone: take in the
  // declarations above it.
  while (end - start + 1 < 6 && start > 0) {
    start -= 1;
    while (start > 0 && !(topLevel(lines[start] ?? "") && !closing(lines[start] ?? ""))) start -= 1;
  }
  if (end - start + 1 > MAX) {
    start = Math.max(start, at - (MAX - 3));
    end = Math.min(end, start + MAX - 1);
  }
  return [
    ...(start > 0 ? ["// …"] : []),
    ...lines.slice(start, end + 1),
    ...(end < lines.length - 1 ? ["// …"] : []),
  ];
}

/** The sentence that leads into the good example ("List the hidden cases …:"), as a sentence. */
function fixSentence(example) {
  const sentence = example.fixLead.replace(/:$/, ".");
  return sentence.charAt(0).toLowerCase() + sentence.slice(1);
}

function packPage(plugin, examples) {
  const importName = importNameOf(plugin);
  const packageName = packageNameOf(plugin);
  const lines = [
    HEADER,
    "",
    `# ${plugin.name}`,
    "",
    plugin.description,
    "",
    "## Turn it on",
    "",
    `Install \`${packageName}\` and add \`${importName}()\` to \`plugins\` in \`stateward.config.ts\`, with a \`preset\` (\`npx stateward init\` does both):`,
    "",
    "```ts",
    `plugins: [${importName}()], preset: "recommended", // or "strict"`,
    "```",
    "",
    `Each rule's page has its options and what it does not catch. One rule or a whole group is set under \`rules\` or \`groups\`: \`rules: { "${plugin.name}/<rule>": "warning" }\`.`,
    "",
    "## Rules",
    "",
    ...rulesTable(plugin, relativeFrom(`docs/packs/${plugin.name}.md`)),
    "",
  ];
  for (const [key, rule] of rulesInPageOrder(plugin)) {
    const example = examples.get(`${plugin.name}/${key}`);
    lines.push(
      `## [${key}](../rules/${plugin.name}/${key}.md)`,
      "",
      rule.meta.description,
      "",
      ...(example === undefined ? [] : [...packExample(example), ""]),
      ruleStatus(plugin, key, rule.meta),
      "",
    );
  }
  if (Object.values(plugin.rules).some((rule) => addonsOf(rule).length > 0)) {
    lines.push(
      "## Add-ons",
      "",
      `List an add-on in \`addons\` to turn on its rules: \`addons: ["${plugin.name}/<add-on>"]\`.`,
      "",
      ...addonLines(plugin),
      "",
    );
  }
  return lines.join("\n");
}

/** The add-ons a rule belongs to (an add-on rule) or is widened by (a core or coverage rule). */
function addonsOf(rule) {
  return [
    ...(rule.meta.addon === undefined ? [] : [rule.meta.addon]),
    ...(rule.meta.widenedBy ?? []),
  ];
}

function addonLines(plugin) {
  const names = [...new Set(Object.values(plugin.rules).flatMap(addonsOf))].sort();
  if (names.length === 0) return ["None yet."];
  return names.map((name) => {
    const rules = ruleEntries(plugin)
      .filter(([, rule]) => addonsOf(rule).includes(name))
      .map(
        ([key, rule]) => `\`${key}\`${rule.meta.addon === name ? "" : " (checks more with it)"}`,
      );
    return `- \`${plugin.name}/${name}\`: ${rules.join(", ")}`;
  });
}

/**
 * A rule's page: its explain text with the title and summary of its meta, the output stateward
 * prints under the bad example, the options table at the end of "Turn it on or off", and when the
 * rule is on below it.
 */
function rulePage(plugin, key, rule, example) {
  const id = `${plugin.name}/${key}`;
  const [recommended] = severityCells(plugin, key, rule.meta);
  // The page opens with the summary line, so the explain text's own summary is not repeated.
  const explain = rule.meta.explain
    .replace(`# ${id}\n`, "")
    .trimStart()
    .replace(`${rule.meta.description}\n`, "")
    .trimStart();
  const blocks = exampleBlocks(explain);
  const lastBad = Math.max(...blocks.filter((b) => b.role === "bad").map((b) => b.endLine));
  const body = [];
  explain
    .trimEnd()
    .split("\n")
    .forEach((line, index) => {
      const block = blocks.find((entry) => entry.line === index);
      if (block !== undefined) {
        body.push(`\`\`\`${block.lang}`);
      } else {
        body.push(line);
      }
      if (index === lastBad) {
        body.push("", "`stateward check` prints:", "", "```text", example.output, "```");
      }
    });
  const lines = [HEADER, "", `# ${id}`, "", rule.meta.description, "", ...body, ""];
  const rows = optionRows(rule.meta.options);
  if (rows.length > 0) {
    // "Turn it on or off" is the last section: the options table closes it.
    lines.push(
      `Options, set as \`rules: { "${id}": ["${recommended === "off" ? "error" : recommended}", { … }] }\`:`,
      "",
      ...OPTION_HEAD,
      ...rows,
      "",
    );
  }
  lines.push(ruleStatus(plugin, key, rule.meta), "");
  return lines.join("\n");
}

// The public repository: npm does not resolve relative links, so a package's README links here.
const PUBLIC_BLOB = "https://github.com/khoing1111/ts-stateward/blob/main";

function packageNameOf(plugin) {
  const entry = PACK_CATALOG.find((pack) => pack.name === plugin.name);
  if (entry === undefined) throw new Error(`pack ${plugin.name} is not in the CLI's catalog`);
  return entry.packageName;
}

/** The kind column: Core, Coverage, or Add-on `name`. */
function kindOf(meta) {
  return meta.tier === "addon" ? `Add-on \`${meta.addon ?? ""}\`` : TIER_TITLES[meta.tier];
}

/** The pack's rules in the order of its page: by group, then core, coverage, add-on. */
function rulesInPageOrder(plugin) {
  return groupNames(plugin).flatMap((group) =>
    RULE_TIERS.flatMap((tier) =>
      ruleEntries(plugin).filter(
        ([, rule]) => rule.meta.group === group && rule.meta.tier === tier,
      ),
    ),
  );
}

/** One pack's rules table; `href(path)` turns a repository path into the link to write. */
function rulesTable(plugin, href) {
  const rows = rulesInPageOrder(plugin).map(([key, rule]) => {
    const [recommended, strict] = severityCells(plugin, key, rule.meta);
    const heuristic = rule.meta.heuristic === true ? " (guess)" : "";
    const link = href(`docs/rules/${plugin.name}/${key}.md`);
    return `| [${key}](${link}) | ${cell(rule.meta.summary ?? rule.meta.description)}${heuristic} | ${cell(rule.meta.description)} | ${kindOf(rule.meta)} | ${recommended} | ${strict} |`;
  });
  return [
    "| Rule | What it finds | Why it matters | Kind | `recommended` | `strict` |",
    "| --- | --- | --- | --- | --- | --- |",
    ...rows,
  ];
}

/** A pack's heading, promise, package and rules table. */
function packRulesBlock(plugin, href, level) {
  return [
    `${"#".repeat(level)} [${plugin.name}](${href(`docs/packs/${plugin.name}.md`)})`,
    "",
    `${plugin.description} Package: \`${packageNameOf(plugin)}\`.`,
    "",
    ...rulesTable(plugin, href),
  ];
}

